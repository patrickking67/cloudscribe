#!/usr/bin/env node
// Builds the browser copy of the compiler used by the playground on the docs
// site. GitHub Pages serves docs/ as static files, so the output is committed.
//
//   node scripts/build-playground.mjs          write docs/playground/
//   node scripts/build-playground.mjs --check  exit 1 if docs/playground/ is stale
//
// The compiler stages are copied unchanged. Only the parser differs: it embeds
// the grammar text and uses the ohm global from the vendored ohm.min.js
// instead of reading the grammar from disk and importing ohm-js.

import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs"

const root = new URL("../", import.meta.url)
const outDir = new URL("docs/playground/", root)
const read = path => readFileSync(new URL(path, root), "utf8")
const header = source => `// Generated by scripts/build-playground.mjs from ${source}. Do not edit.\n`

const ohmVersion = JSON.parse(read("node_modules/ohm-js/package.json")).version

const parser = `${header("src/parser.js and src/cloudscribe.ohm")}
// Load ohm.min.js (ohm-js ${ohmVersion}) with a classic script tag before this module.
const ohm = globalThis.ohm
if (!ohm?.grammar) throw new Error("The CloudScribe playground needs ohm.min.js loaded first")

const grammar = ohm.grammar(${JSON.stringify(read("src/cloudscribe.ohm"))})

export default function parse(sourceCode) {
  const match = grammar.match(sourceCode)
  if (!match.succeeded()) throw new Error(match.message)
  return match
}
`

const files = {
  "parser.js": parser,
  "ohm.min.js": read("node_modules/ohm-js/dist/ohm.min.js"),
  "ohm-LICENSE.txt": read("node_modules/ohm-js/LICENSE")
}
for (const stage of ["compiler", "analyzer", "optimizer", "generator", "core"]) {
  files[`${stage}.js`] = header(`src/${stage}.js`) + read(`src/${stage}.js`)
}

const check = process.argv.includes("--check")
const stale = Object.entries(files).filter(([name, text]) => {
  const file = new URL(name, outDir)
  return !existsSync(file) || readFileSync(file, "utf8") !== text
})

if (check) {
  if (stale.length > 0) {
    console.error(`docs/playground is out of date: ${stale.map(([name]) => name).join(", ")}`)
    console.error("Run npm run build:playground and commit the result.")
    process.exit(1)
  }
  console.log("docs/playground is up to date.")
} else {
  mkdirSync(outDir, { recursive: true })
  for (const [name, text] of stale) writeFileSync(new URL(name, outDir), text)
  console.log(`Wrote ${stale.length} file(s) to docs/playground/.`)
}
